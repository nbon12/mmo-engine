using System.Globalization;
using System.Text;

namespace MmoEngine.Regionizer.Simulator.Analysis.Memo;

/// <summary>
/// Writes the decision memo (FR-032, SC-005): one row per value in the rules, each with its recommended
/// value labeled as a measurement, whether it is a recommendation or a reading, the population it was read
/// at, the curve it was read from (x, mean, min and max over seeds), its margin, its seeds and its run IDs;
/// then the measured options side by side. A value or option whose results cannot be read gets a clearly
/// marked entry, and the result does not succeed.
/// </summary>
public static class MemoGenerator
{
    /// <summary>The label every recommended value carries (Principle VI: every number is an estimate or a measurement).</summary>
    public const string MeasurementLabel = "(measurement)";

    /// <summary>Reads every value's and measured option's sweeps under <paramref name="resultsDirectory"/> and builds the memo.</summary>
    public static MemoResult Generate(string resultsDirectory, MemoRules rules)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(resultsDirectory);
        ArgumentNullException.ThrowIfNull(rules);
        var rows = rules.Values.Select(rule => MemoEvaluator.Evaluate(resultsDirectory, rule)).ToList();
        var options = rules.MeasuredOptions.Select(rule => MeasuredOptionEvaluator.Evaluate(resultsDirectory, rule)).ToList();
        var name = Path.GetFileName(Path.TrimEndingDirectorySeparator(Path.GetFullPath(resultsDirectory)));
        return new MemoResult(rows, options, Markdown(name, rows, options));
    }

    /// <summary>Builds the memo and writes it to <paramref name="outPath"/>, creating its folder.</summary>
    public static MemoResult Write(string resultsDirectory, MemoRules rules, string outPath)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outPath);
        var result = Generate(resultsDirectory, rules);
        var folder = Path.GetDirectoryName(Path.GetFullPath(outPath));
        if (!string.IsNullOrEmpty(folder))
        {
            Directory.CreateDirectory(folder);
        }

        File.WriteAllText(outPath, result.Markdown);
        return result;
    }

    private static string Markdown(string resultsName, List<MemoRow> rows, List<MeasuredOptionResult> options)
    {
        var md = new StringBuilder();
        md.Append("# Regionizer decision memo\n\n");
        md.Append("Generated by `regionizer-sim memo` from the sweep results in `").Append(resultsName)
            .Append("`, read with the rules of research D15. Every recommended value is a measurement read off the curve shown ")
            .Append("with it (x, and the mean, min and max over seeds), with its margin, seeds and run IDs, at the population its row ")
            .Append("names, which every run's manifest confirms. Values for open decision 1 are recommendations recorded under Principle VI ")
            .Append("and stay in configuration. The target fight size is a reading for the Phase 1 sweep; open decision 2 is set by load ")
            .Append("tests. Merge rates count real merges, not absorptions. The measured options at the end are reported side by side, ")
            .Append("with no recommendation.\n\n");

        var unreadable = rows.Count(r => r.Status == MemoRowStatus.Unreadable);
        var unreadableOptions = options.Count(o => !o.Readable);
        var optionsText = options.Count == 0 ? string.Empty : $" and {options.Count} measured options";
        md.Append(unreadable + unreadableOptions == 0
            ? $"All {rows.Count} values{optionsText} were read.\n\n"
            : $"**{unreadable} of {rows.Count} values{(options.Count == 0 ? string.Empty : $" and {unreadableOptions} of {options.Count} measured options")} "
                + "could not be read.** They are marked UNREADABLE.\n\n");

        md.Append("| Value | Population | Recommended | Label | Status | Margin |\n| --- | --- | --- | --- | --- | --- |\n");
        foreach (var row in rows)
        {
            md.Append("| ").Append(Cell(row.Title))
                .Append(" | ").Append(row.Population.ToString(CultureInfo.InvariantCulture))
                .Append(" | ").Append(row.Status == MemoRowStatus.Unreadable ? "**not read**" : Cell(row.Recommended))
                .Append(" | ").Append(Cell(row.LabelText))
                .Append(" | ").Append(StatusText(row))
                .Append(" | ").Append(Cell(row.Problem ?? row.Margin))
                .Append(" |\n");
        }

        foreach (var row in rows)
        {
            ValueSection(md, row);
        }

        if (options.Count > 0)
        {
            md.Append("\n## Measured options\n\n");
            md.Append("Reported side by side, with no recommendation (research D15). Each metric is the mean over the seeds that ")
                .Append("completed cleanly, with their min and max in brackets; runs that stopped at a timer fault or an invariant ")
                .Append("violation are counted separately.\n");
            foreach (var option in options)
            {
                OptionSection(md, option);
            }
        }

        return md.ToString();
    }

    private static void ValueSection(StringBuilder md, MemoRow row)
    {
        md.Append("\n## ").Append(row.Title).Append("\n\n");
        md.Append("- **Recommended**: ").Append(row.Status == MemoRowStatus.Unreadable ? "**not read**" : row.Recommended).Append('\n');
        md.Append("- **Label**: ").Append(row.LabelText).Append('\n');
        md.Append("- **Status**: ").Append(StatusText(row)).Append('\n');
        md.Append("- **Population**: ").Append(Population(row.Population, row.Status != MemoRowStatus.Unreadable)).Append('\n');
        if (row.Problem is not null)
        {
            md.Append("- **Why**: ").Append(row.Problem).Append('\n');
        }

        md.Append("- **Rule**: ").Append(row.Rule.Length == 0 ? "see research D15" : row.Rule).Append('\n');
        md.Append("- **Read from**: ").Append(row.Source).Append('\n');
        md.Append("- **Margin**: ").Append(row.Margin.Length == 0 ? "none" : row.Margin).Append('\n');
        if (row.MergeCounting is not null)
        {
            md.Append("- **Merge counting**: ").Append(row.MergeCounting).Append('\n');
        }

        if (row.Note is not null)
        {
            md.Append("- **Principle VI**: ").Append(row.Note).Append('\n');
        }

        if (row.RegionCountNote is not null)
        {
            md.Append("- **Region count**: ").Append(row.RegionCountNote).Append('\n');
        }

        md.Append("- **Seeds**: ").Append(row.Seeds.Count == 0 ? "none" : string.Join(", ", row.Seeds)).Append('\n');
        md.Append("- **Runs**: ").Append(row.RunIds.Count == 0 ? "none" : string.Join(", ", row.RunIds.Select(id => $"`{id}`"))).Append('\n');
        md.Append('\n');
        if (row.Curve.Count == 0)
        {
            md.Append("No curve: the results could not be read.\n");
            return;
        }

        var series = row.Curve.Any(p => p.Series.Length > 0);
        md.Append(series ? "| Series | x | Mean | Min | Max | Seeds |\n| --- | --- | --- | --- | --- | --- |\n" : "| x | Mean | Min | Max | Seeds |\n| --- | --- | --- | --- | --- |\n");
        foreach (var point in row.Curve)
        {
            md.Append('|');
            if (series)
            {
                md.Append(' ').Append(Cell(point.Series)).Append(" |");
            }

            md.Append(' ').Append(Cell(point.X))
                .Append(" | ").Append(SweepResults.Number(point.Mean))
                .Append(" | ").Append(SweepResults.Number(point.Min))
                .Append(" | ").Append(SweepResults.Number(point.Max))
                .Append(" | ").Append(point.Seeds)
                .Append(" |\n");
        }

        if (row.Reading.Count == 0)
        {
            return;
        }

        md.Append("\nConstitution reading: the fused-fight-pairs, region-count and largest-share curves the constitution's ")
            .Append("Validation program reads, each the mean over seeds with the min and max in brackets.\n\n");
        var readingSeries = row.Reading.Any(p => p.Series.Length > 0);
        md.Append(readingSeries ? "| Series | x | Fused fight pairs | Region count | Largest share |\n| --- | --- | --- | --- | --- |\n"
            : "| x | Fused fight pairs | Region count | Largest share |\n| --- | --- | --- | --- |\n");
        foreach (var point in row.Reading)
        {
            md.Append('|');
            if (readingSeries)
            {
                md.Append(' ').Append(Cell(point.Series)).Append(" |");
            }

            md.Append(' ').Append(Cell(point.X))
                .Append(" | ").Append(Stat(point.FusedFightPairs))
                .Append(" | ").Append(Stat(point.RegionCount))
                .Append(" | ").Append(Stat(point.LargestShare))
                .Append(" |\n");
        }
    }

    private static void OptionSection(StringBuilder md, MeasuredOptionResult option)
    {
        md.Append("\n### ").Append(option.Title).Append("\n\n");
        md.Append("- **Status**: ").Append(option.Readable ? "Read" : "**UNREADABLE**").Append('\n');
        if (option.Problem is not null)
        {
            md.Append("- **Why**: ").Append(option.Problem).Append('\n');
        }

        md.Append("- **Population**: ").Append(Population(option.Population, option.Readable)).Append('\n');
        md.Append("- **Read from**: ").Append(option.Source).Append('\n');
        if (option.Description.Length > 0)
        {
            md.Append("- **About**: ").Append(option.Description).Append('\n');
        }

        if (option.MergeCounting is not null)
        {
            md.Append("- **Merge counting**: ").Append(option.MergeCounting).Append('\n');
        }

        md.Append("- **Seeds**: ").Append(option.Seeds.Count == 0 ? "none" : string.Join(", ", option.Seeds)).Append('\n');
        md.Append("- **Runs**: ").Append(option.RunIds.Count == 0 ? "none" : string.Join(", ", option.RunIds.Select(id => $"`{id}`"))).Append('\n');
        md.Append('\n');
        if (option.Table.Count == 0)
        {
            md.Append("No table: the results could not be read.\n");
            return;
        }

        md.Append("| Metric | ").Append(string.Join(" | ", option.Options.Select(Cell))).Append(" |\n|");
        md.Append(string.Concat(Enumerable.Repeat(" --- |", option.Options.Count + 1))).Append('\n');
        foreach (var row in option.Table)
        {
            md.Append("| ").Append(Cell(row.Metric)).Append(" | ").Append(string.Join(" | ", row.Cells.Select(Cell))).Append(" |\n");
        }
    }

    private static string Population(int population, bool confirmed) =>
        population.ToString(CultureInfo.InvariantCulture) + (confirmed
            ? " (`population.total`, as every run's manifest records)"
            : " (`population.total` the rules read it at; not confirmed, the results could not be read)");

    private static string Stat(CurveStat stat) =>
        $"{SweepResults.Number(stat.Mean)} ({SweepResults.Number(stat.Min)} to {SweepResults.Number(stat.Max)})";

    /// <summary>A value read off its curve is Recommended, or Read for a reading; otherwise FLAGGED or UNREADABLE.</summary>
    private static string StatusText(MemoRow row) => row.Status switch
    {
        MemoRowStatus.Recommended => row.Label == MemoLabel.Reading ? "Read" : "Recommended",
        MemoRowStatus.Flagged => "**FLAGGED**",
        _ => "**UNREADABLE**",
    };

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace('\n', ' ');
}
