using System.Text;

namespace MmoEngine.Regionizer.Simulator.Analysis.Memo;

/// <summary>
/// Writes the decision memo (FR-032, SC-005): one row per value in the rules, each with its recommended
/// value labeled as a measurement, the curve it was read from (x, mean, min and max over seeds), its
/// margin, its seeds and its run IDs. A value whose results cannot be read gets a clearly marked row,
/// and the result does not succeed.
/// </summary>
public static class MemoGenerator
{
    /// <summary>The label every recommended value carries (Principle VI: every number is an estimate or a measurement).</summary>
    public const string MeasurementLabel = "(measurement)";

    /// <summary>Reads every value's sweeps under <paramref name="resultsDirectory"/> and builds the memo.</summary>
    public static MemoResult Generate(string resultsDirectory, MemoRules rules)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(resultsDirectory);
        ArgumentNullException.ThrowIfNull(rules);
        var rows = rules.Values.Select(rule => MemoEvaluator.Evaluate(resultsDirectory, rule)).ToList();
        var name = Path.GetFileName(Path.TrimEndingDirectorySeparator(Path.GetFullPath(resultsDirectory)));
        return new MemoResult(rows, Markdown(name, rows));
    }

    /// <summary>Builds the memo and writes it to <paramref name="outPath"/>, creating its folder.</summary>
    public static MemoResult Write(string resultsDirectory, MemoRules rules, string outPath)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outPath);
        var result = Generate(resultsDirectory, rules);
        var folder = Path.GetDirectoryName(Path.GetFullPath(outPath));
        if (!string.IsNullOrEmpty(folder))
        {
            Directory.CreateDirectory(folder);
        }

        File.WriteAllText(outPath, result.Markdown);
        return result;
    }

    private static string Markdown(string resultsName, List<MemoRow> rows)
    {
        var md = new StringBuilder();
        md.Append("# Regionizer decision memo\n\n");
        md.Append("Generated by `regionizer-sim memo` from the sweep results in `").Append(resultsName)
            .Append("`, read with the rules of research D15. Every recommended value is a measurement read off the curve shown ")
            .Append("with it (x, and the mean, min and max over seeds), with its margin, seeds and run IDs. Values for open decision 1 ")
            .Append("are recommendations recorded under Principle VI and stay in configuration. The target fight size is a reading ")
            .Append("for the Phase 1 sweep; open decision 2 is set by load tests.\n\n");

        var unreadable = rows.Count(r => r.Status == MemoRowStatus.Unreadable);
        md.Append(unreadable == 0
            ? $"All {rows.Count} values were read.\n\n"
            : $"**{unreadable} of {rows.Count} values could not be read.** Their rows are marked UNREADABLE.\n\n");

        md.Append("| Value | Recommended | Status | Margin |\n| --- | --- | --- | --- |\n");
        foreach (var row in rows)
        {
            md.Append("| ").Append(Cell(row.Title))
                .Append(" | ").Append(row.Status == MemoRowStatus.Unreadable ? "**not read**" : Cell(row.Recommended))
                .Append(" | ").Append(StatusText(row.Status))
                .Append(" | ").Append(Cell(row.Problem ?? row.Margin))
                .Append(" |\n");
        }

        foreach (var row in rows)
        {
            md.Append("\n## ").Append(row.Title).Append("\n\n");
            md.Append("- **Recommended**: ").Append(row.Status == MemoRowStatus.Unreadable ? "**not read**" : row.Recommended).Append('\n');
            md.Append("- **Status**: ").Append(StatusText(row.Status)).Append('\n');
            if (row.Problem is not null)
            {
                md.Append("- **Why**: ").Append(row.Problem).Append('\n');
            }

            md.Append("- **Rule**: ").Append(row.Rule.Length == 0 ? "see research D15" : row.Rule).Append('\n');
            md.Append("- **Read from**: ").Append(row.Source).Append('\n');
            md.Append("- **Margin**: ").Append(row.Margin.Length == 0 ? "none" : row.Margin).Append('\n');
            if (row.Note is not null)
            {
                md.Append("- **Principle VI**: ").Append(row.Note).Append('\n');
            }

            md.Append("- **Seeds**: ").Append(row.Seeds.Count == 0 ? "none" : string.Join(", ", row.Seeds)).Append('\n');
            md.Append("- **Runs**: ").Append(row.RunIds.Count == 0 ? "none" : string.Join(", ", row.RunIds.Select(id => $"`{id}`"))).Append('\n');
            md.Append('\n');
            if (row.Curve.Count == 0)
            {
                md.Append("No curve: the results could not be read.\n");
                continue;
            }

            var series = row.Curve.Any(p => p.Series.Length > 0);
            md.Append(series ? "| Series | x | Mean | Min | Max | Seeds |\n| --- | --- | --- | --- | --- | --- |\n" : "| x | Mean | Min | Max | Seeds |\n| --- | --- | --- | --- | --- |\n");
            foreach (var point in row.Curve)
            {
                md.Append('|');
                if (series)
                {
                    md.Append(' ').Append(Cell(point.Series)).Append(" |");
                }

                md.Append(' ').Append(Cell(point.X))
                    .Append(" | ").Append(SweepResults.Number(point.Mean))
                    .Append(" | ").Append(SweepResults.Number(point.Min))
                    .Append(" | ").Append(SweepResults.Number(point.Max))
                    .Append(" | ").Append(point.Seeds)
                    .Append(" |\n");
            }
        }

        return md.ToString();
    }

    private static string StatusText(MemoRowStatus status) => status switch
    {
        MemoRowStatus.Recommended => "Recommended",
        MemoRowStatus.Flagged => "**FLAGGED**",
        _ => "**UNREADABLE**",
    };

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace('\n', ' ');
}
