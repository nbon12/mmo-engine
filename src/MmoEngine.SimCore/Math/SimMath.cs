using System;
using static MmoEngine.SimCore.Math.SimMathCoefficients;

namespace MmoEngine.SimCore.Math;

/// <summary>
/// The core's own float32 math (FR-013, specs/015-shared-simulation-core/research.md R3 and R4). Every
/// function has one fixed algorithm, so the server and every WebAssembly build return the same bits
/// for the same input: scalar <see cref="float"/> arithmetic, no fused multiply-add, polynomials by
/// Horner with every operation parenthesised, and integer arithmetic where a float result would need
/// more precision than float32 has.
/// <list type="bullet">
/// <item><description>Sin, Cos, SinCos and Tan reduce |x| ≤ π/4 not at all, |x| ≤ 12867 by a 4-part
/// Cody–Waite split of π/2 with a Fast2Sum tail, and larger |x| by an exact integer Payne–Hanek
/// reduction against 320 bits of 2/π. The kernels take the reduced argument with its tail.</description></item>
/// <item><description>Asin and Acos share one polynomial, with a square-root correction above ½. Atan
/// reduces at fdlibm's breakpoints 7/16, 11/16, 19/16 and 39/16. Atan2 follows C99 Annex F.</description></item>
/// <item><description>SinCosBinaryAngle reduces a 16-bit binary angle to its quadrant in integers.</description></item>
/// <item><description>Non-finite input to a radian function gives the <see cref="float.NaN"/> constant;
/// Atan(±∞) is ±π/2.</description></item>
/// <item><description>Min and Max are compare-selects, and the three float-to-int conversions saturate
/// before they cast (research R4).</description></item>
/// </list>
/// The coefficients and split constants are generated by tools/simcore/ into
/// <see cref="SimMathCoefficients"/> and <see cref="TwoOverPi"/>.
/// </summary>
public static class SimMath
{
    /// <summary>The largest |x| the Cody–Waite reduction takes: k = round(x·2/π) stays below 2^13, so k times each 11-bit part of π/2 is exact.</summary>
    private const float CodyWaiteLimit = 12867f;

    /// <summary>Above this |x|, atan(x) rounds to π/2.</summary>
    private const float AtanHugeLimit = 67108864f;

    /// <summary>Clears the low 12 bits of a float's significand, leaving 12 significant bits, so the product of two such values is exact.</summary>
    private const uint TwelveBitMask = 0xFFFFF000u;

    /// <summary>
    /// π/2 in Q62 fixed point for the Payne–Hanek path: the exact sum of the four Cody–Waite parts,
    /// whose lowest bit is 2^-62, so both reductions use one pinned definition of π/2 (|error| ≤ 2^-63).
    /// </summary>
    private static readonly ulong HalfPiQ62 = Q62(HalfPiPart1) + Q62(HalfPiPart2) + Q62(HalfPiPart3) + Q62(HalfPiPart4);

    /// <summary>The sine of <paramref name="x"/> radians. NaN for a non-finite input.</summary>
    /// <remarks>
    /// Maximum error: <see cref="SimMathBounds.SinCosMaxUlp"/> ulp for |x| ≤ <see cref="SimMathBounds.ReductionLimit"/>,
    /// and <see cref="SimMathBounds.SinCosLargeMaxUlp"/> ulp for larger finite |x|.
    /// </remarks>
    public static float Sin(float x)
    {
        if (!float.IsFinite(x))
        {
            return float.NaN;
        }

        var ax = float.Abs(x);
        float result;
        if (ax <= QuarterPiHi)
        {
            result = SinKernel(ax, 0f);
        }
        else
        {
            var quadrant = Reduce(ax, out var r, out var tail);
            result = (quadrant & 1) == 0 ? SinKernel(r, tail) : CosKernel(r, tail);
            if ((quadrant & 2) != 0)
            {
                result = -result;
            }
        }

        return float.IsNegative(x) ? -result : result;
    }

    /// <summary>The cosine of <paramref name="x"/> radians. NaN for a non-finite input.</summary>
    /// <remarks>
    /// Maximum error: <see cref="SimMathBounds.SinCosMaxUlp"/> ulp for |x| ≤ <see cref="SimMathBounds.ReductionLimit"/>,
    /// and <see cref="SimMathBounds.SinCosLargeMaxUlp"/> ulp for larger finite |x|.
    /// </remarks>
    public static float Cos(float x)
    {
        if (!float.IsFinite(x))
        {
            return float.NaN;
        }

        var ax = float.Abs(x);
        if (ax <= QuarterPiHi)
        {
            return CosKernel(ax, 0f);
        }

        var quadrant = Reduce(ax, out var r, out var tail);
        var result = (quadrant & 1) == 0 ? CosKernel(r, tail) : SinKernel(r, tail);
        return ((quadrant + 1) & 2) != 0 ? -result : result;
    }

    /// <summary>
    /// The sine and cosine of <paramref name="x"/> radians from one reduction, bit for bit equal to
    /// <see cref="Sin"/> and <see cref="Cos"/>. Both are NaN for a non-finite input.
    /// </summary>
    /// <remarks>
    /// Maximum error: <see cref="SimMathBounds.SinCosMaxUlp"/> ulp for |x| ≤ <see cref="SimMathBounds.ReductionLimit"/>,
    /// and <see cref="SimMathBounds.SinCosLargeMaxUlp"/> ulp for larger finite |x|.
    /// </remarks>
    public static void SinCos(float x, out float sin, out float cos)
    {
        if (!float.IsFinite(x))
        {
            sin = float.NaN;
            cos = float.NaN;
            return;
        }

        var ax = float.Abs(x);
        float s;
        float c;
        if (ax <= QuarterPiHi)
        {
            s = SinKernel(ax, 0f);
            c = CosKernel(ax, 0f);
        }
        else
        {
            var quadrant = Reduce(ax, out var r, out var tail);
            var kernelSin = SinKernel(r, tail);
            var kernelCos = CosKernel(r, tail);
            if ((quadrant & 1) == 0)
            {
                s = kernelSin;
                c = kernelCos;
            }
            else
            {
                s = kernelCos;
                c = kernelSin;
            }

            if ((quadrant & 2) != 0)
            {
                s = -s;
            }

            if (((quadrant + 1) & 2) != 0)
            {
                c = -c;
            }
        }

        sin = float.IsNegative(x) ? -s : s;
        cos = c;
    }

    /// <summary>The tangent of <paramref name="x"/> radians. NaN for a non-finite input.</summary>
    /// <remarks>
    /// Maximum error: <see cref="SimMathBounds.TanMaxUlp"/> ulp for |x| ≤ <see cref="SimMathBounds.ReductionLimit"/>,
    /// and <see cref="SimMathBounds.TanLargeMaxUlp"/> ulp for larger finite |x|.
    /// </remarks>
    public static float Tan(float x)
    {
        if (!float.IsFinite(x))
        {
            return float.NaN;
        }

        var ax = float.Abs(x);
        float result;
        if (ax <= QuarterPiHi)
        {
            result = TanKernel(ax, 0f, odd: false);
        }
        else
        {
            var quadrant = Reduce(ax, out var r, out var tail);
            result = TanKernel(r, tail, odd: (quadrant & 1) != 0);
        }

        return float.IsNegative(x) ? -result : result;
    }

    /// <summary>The arcsine of <paramref name="x"/> in [−π/2, π/2]. NaN outside [−1, 1] and for NaN.</summary>
    /// <remarks>Maximum error: <see cref="SimMathBounds.AsinAcosMaxUlp"/> ulp on [−1, 1].</remarks>
    public static float Asin(float x)
    {
        var ax = float.Abs(x);
        if (!(ax <= 1f))
        {
            return float.NaN;
        }

        float result;
        if (ax <= 0.5f)
        {
            result = ax + (ax * AsinPolynomial(ax * ax));
        }
        else
        {
            // asin(x) = π/2 − 2·asin(s) with s = √((1 − x)/2); 1 − x and the halving are exact.
            var z = (1f - ax) * 0.5f;
            var s = Sqrt(z);
            var r = AsinPolynomial(z);
            if (ax >= 0.975f)
            {
                result = HalfPiHi - ((2f * (s + (s * r))) - HalfPiLo);
            }
            else
            {
                // The square-root correction: w + c is √z to about twice float precision.
                var w = KeepTwelveBits(s);
                var c = (z - (w * w)) / (s + w);
                var p = (2f * (s * r)) - (HalfPiLo - (2f * c));
                var q = QuarterPiHi - (2f * w);
                result = QuarterPiHi - (p - q);
            }
        }

        return float.IsNegative(x) ? -result : result;
    }

    /// <summary>The arccosine of <paramref name="x"/> in [0, π]. NaN outside [−1, 1] and for NaN.</summary>
    /// <remarks>Maximum error: <see cref="SimMathBounds.AsinAcosMaxUlp"/> ulp on [−1, 1].</remarks>
    public static float Acos(float x)
    {
        var ax = float.Abs(x);
        if (!(ax <= 1f))
        {
            return float.NaN;
        }

        if (ax <= 0.5f)
        {
            // acos(x) = π/2 − asin(x).
            return HalfPiHi - (x - (HalfPiLo - (x * AsinPolynomial(x * x))));
        }

        if (float.IsNegative(x))
        {
            // acos(x) = π − 2·asin(s) with s = √((1 + x)/2).
            var z = (1f + x) * 0.5f;
            var s = Sqrt(z);
            var w = (AsinPolynomial(z) * s) - HalfPiLo;
            return PiHi - (2f * (s + w));
        }

        if (x == 1f)
        {
            return 0f;
        }

        // acos(x) = 2·asin(s) with s = √((1 − x)/2), and the square-root correction.
        var zp = (1f - x) * 0.5f;
        var sp = Sqrt(zp);
        var high = KeepTwelveBits(sp);
        var correction = (zp - (high * high)) / (sp + high);
        var rest = (AsinPolynomial(zp) * sp) + correction;
        return 2f * (high + rest);
    }

    /// <summary>The arctangent of <paramref name="x"/> in [−π/2, π/2]; Atan(±∞) is ±π/2. NaN for NaN.</summary>
    /// <remarks>Maximum error: <see cref="SimMathBounds.AtanMaxUlp"/> ulp on every float.</remarks>
    public static float Atan(float x)
    {
        if (float.IsNaN(x))
        {
            return float.NaN;
        }

        var ax = float.Abs(x);
        float result;
        if (ax >= AtanHugeLimit)
        {
            result = HalfPiHi + HalfPiLo;
        }
        else if (ax < 0.4375f)
        {
            result = ax - (ax * AtanPolynomial(ax * ax));
        }
        else
        {
            // atan(x) = atan(c) + atan(t) at fdlibm's breakpoints, with atan(c) as a hi + lo pair.
            float t;
            float high;
            float low;
            if (ax < 1.1875f)
            {
                if (ax < 0.6875f)
                {
                    t = ((2f * ax) - 1f) / (2f + ax);
                    high = AtanHalfHi;
                    low = AtanHalfLo;
                }
                else
                {
                    t = (ax - 1f) / (ax + 1f);
                    high = QuarterPiHi;
                    low = QuarterPiLo;
                }
            }
            else if (ax < 2.4375f)
            {
                t = (ax - 1.5f) / (1f + (1.5f * ax));
                high = AtanThreeHalvesHi;
                low = AtanThreeHalvesLo;
            }
            else
            {
                t = -1f / ax;
                high = HalfPiHi;
                low = HalfPiLo;
            }

            result = high - (((t * AtanPolynomial(t * t)) - low) - t);
        }

        return float.IsNegative(x) ? -result : result;
    }

    /// <summary>
    /// The angle of the point (<paramref name="x"/>, <paramref name="y"/>) in [−π, π], following C99
    /// Annex F: signed zeros and infinities give the annex's exact results, and NaN in either argument
    /// gives NaN.
    /// </summary>
    /// <remarks>Maximum error: <see cref="SimMathBounds.Atan2MaxUlp"/> ulp.</remarks>
    public static float Atan2(float y, float x)
    {
        if (float.IsNaN(x) || float.IsNaN(y))
        {
            return float.NaN;
        }

        if (x == 1f)
        {
            return Atan(y);
        }

        // Bit 0: y is negative. Bit 1: x is negative.
        var m = (float.IsNegative(y) ? 1 : 0) | (float.IsNegative(x) ? 2 : 0);
        if (y == 0f)
        {
            return m switch
            {
                0 or 1 => y,
                2 => PiHi,
                _ => -PiHi,
            };
        }

        if (x == 0f)
        {
            return float.IsNegative(y) ? -HalfPiHi : HalfPiHi;
        }

        if (float.IsInfinity(x))
        {
            if (float.IsInfinity(y))
            {
                return m switch
                {
                    0 => QuarterPiHi,
                    1 => -QuarterPiHi,
                    2 => ThreeQuarterPi,
                    _ => -ThreeQuarterPi,
                };
            }

            return m switch
            {
                0 => 0f,
                1 => -0f,
                2 => PiHi,
                _ => -PiHi,
            };
        }

        if (float.IsInfinity(y))
        {
            return float.IsNegative(y) ? -HalfPiHi : HalfPiHi;
        }

        // The difference of the biased exponents bounds |y/x| without dividing.
        var k = ((int)(BitConverter.SingleToUInt32Bits(y) >> 23) & 0xFF) - ((int)(BitConverter.SingleToUInt32Bits(x) >> 23) & 0xFF);
        float z;
        if (k > 26)
        {
            z = HalfPiHi + (0.5f * PiLo);
            m &= 1;
        }
        else if (m >= 2 && k < -26)
        {
            z = 0f;
        }
        else
        {
            z = Atan(float.Abs(y / x));
        }

        return m switch
        {
            0 => z,
            1 => -z,
            2 => PiHi - (z - PiLo),
            _ => (z - PiLo) - PiHi,
        };
    }

    /// <summary>
    /// The sine and cosine of the binary angle <paramref name="angle"/>, in units of 2π/65536. The
    /// quadrant is <c>(angle + 0x2000) &gt;&gt; 14</c> and the rest is reduced in integers, so the four
    /// quadrant angles are exact and adding 16384 gives exactly (cos, −sin). All aim maths uses it.
    /// </summary>
    /// <remarks>Maximum error: <see cref="SimMathBounds.SinCosBinaryAngleMaxUlp"/> ulp on every angle.</remarks>
    public static void SinCosBinaryAngle(ushort angle, out float sin, out float cos)
    {
        var quadrant = (angle + 0x2000) >> 14;
        var units = angle - (quadrant << 14);

        // units·π/32768 as hi + lo: the 8-bit high part makes units·BinaryAngleHi exact.
        float fu = units;
        var high = fu * BinaryAngleHi;
        var low = fu * BinaryAngleLo;
        var r = high + low;
        var tail = low - (r - high);
        var kernelSin = SinKernel(r, tail);
        var kernelCos = CosKernel(r, tail);
        switch (quadrant & 3)
        {
            case 0:
                sin = kernelSin;
                cos = kernelCos;
                break;
            case 1:
                sin = kernelCos;
                cos = -kernelSin;
                break;
            case 2:
                sin = -kernelSin;
                cos = -kernelCos;
                break;
            default:
                sin = -kernelCos;
                cos = kernelSin;
                break;
        }
    }

    /// <summary>The correctly rounded square root. NaN below −0; Sqrt(−0) is −0.</summary>
    /// <remarks>Maximum error: <see cref="SimMathBounds.SqrtMaxUlp"/> ulp.</remarks>
    public static float Sqrt(float x) => System.MathF.Sqrt(x);

    /// <summary><c>a &lt; b ? a : b</c>: the same bits in every build for signed zeros and NaNs.</summary>
    public static float Min(float a, float b) => a < b ? a : b;

    /// <summary><c>a &gt; b ? a : b</c>: the same bits in every build for signed zeros and NaNs.</summary>
    public static float Max(float a, float b) => a > b ? a : b;

    /// <summary>
    /// <c>value &lt; min ? min : (value &gt; max ? max : value)</c>: <paramref name="value"/> limited to
    /// [<paramref name="min"/>, <paramref name="max"/>], with the same bits in every build. It never throws:
    /// a value below <paramref name="min"/> gives <paramref name="min"/>, otherwise a value above
    /// <paramref name="max"/> gives <paramref name="max"/>, even when the bounds cross. A NaN value is
    /// returned unchanged, a NaN bound only skips its own comparison, and a signed zero inside the range
    /// keeps its sign. Whenever min ≤ max it gives the bits <c>System.Math.Clamp</c> gives, which throws
    /// (and allocates) when min &gt; max, so step code never calls it.
    /// </summary>
    public static float Clamp(float value, float min, float max) => value < min ? min : (value > max ? max : value);

    /// <summary>
    /// The largest integer not above <paramref name="x"/>, saturated: NaN gives 0, 2^31 and above give
    /// <see cref="int.MaxValue"/>, below −2^31 gives <see cref="int.MinValue"/>.
    /// </summary>
    public static int FloorToInt(float x)
    {
        if (float.IsNaN(x))
        {
            return 0;
        }

        if (x >= 2147483648f)
        {
            return int.MaxValue;
        }

        if (x < -2147483648f)
        {
            return int.MinValue;
        }

        return (int)System.MathF.Floor(x);
    }

    /// <summary>
    /// The nearest integer to <paramref name="x"/>, ties to even, saturated: NaN gives 0, 2^31 and
    /// above give <see cref="int.MaxValue"/>, below −2^31 gives <see cref="int.MinValue"/>.
    /// </summary>
    public static int RoundToInt(float x)
    {
        if (float.IsNaN(x))
        {
            return 0;
        }

        if (x >= 2147483648f)
        {
            return int.MaxValue;
        }

        if (x < -2147483648f)
        {
            return int.MinValue;
        }

        return (int)System.MathF.Round(x);
    }

    /// <summary>
    /// <paramref name="x"/> rounded toward zero, saturated: NaN gives 0, 2^31 and above give
    /// <see cref="int.MaxValue"/>, below −2^31 gives <see cref="int.MinValue"/>.
    /// </summary>
    public static int TruncateToInt(float x)
    {
        if (float.IsNaN(x))
        {
            return 0;
        }

        if (x >= 2147483648f)
        {
            return int.MaxValue;
        }

        if (x < -2147483648f)
        {
            return int.MinValue;
        }

        return (int)System.MathF.Truncate(x);
    }

    /// <summary>
    /// Reduces a finite |x| above π/4 to r + tail in [−π/4, π/4] (slightly beyond for the Cody–Waite
    /// quadrant count) and returns the quadrant count, of which the low two bits are used.
    /// </summary>
    private static int Reduce(float ax, out float r, out float tail)
    {
        if (ax > CodyWaiteLimit)
        {
            return PayneHanek(ax, out r, out tail);
        }

        // k < 2^13 and each of the first three parts has 11 bits, so k·part is exact, and
        // (ax − k·P1) − k·P2 is exact too. TwoSum takes off k·P3, then k·P4 joins the tail.
        var k = RoundToInt(ax * TwoOverPiSingle);
        float fk = k;
        var y = (ax - (fk * HalfPiPart1)) - (fk * HalfPiPart2);
        var a = fk * HalfPiPart3;
        var b = fk * HalfPiPart4;
        var h = y - a;
        var hv = h - y;
        var l = (y - (h - hv)) - (a + hv);
        var t = l - b;
        r = h + t;
        tail = t - (r - h);
        return k;
    }

    /// <summary>
    /// The exact integer reduction for |x| above the Cody–Waite limit: x = m·2^e with a 24-bit m, times
    /// the 96 bits of 2/π that can change x·(2/π) mod 4, in <see cref="UInt128"/>. The fraction is
    /// rounded to the nearest quadrant, multiplied by π/2 in Q62, and rounded once to float (the tail
    /// keeps the next 24 bits).
    /// </summary>
    private static int PayneHanek(float ax, out float r, out float tail)
    {
        var bits = BitConverter.SingleToUInt32Bits(ax);
        var exponent = (int)(bits >> 23) - 150;
        var significand = (UInt128)((bits & 0x007FFFFFu) | 0x00800000u);

        // Bit j of 2/π (weight 2^-j) adds a multiple of 4 to x·(2/π) when j ≤ e − 2, so the window
        // starts at bit first = max(e − 1, 1), counted from 1.
        var first = exponent - 1 > 1 ? exponent - 1 : 1;
        var position = first - 1;
        var word = position >> 5;
        var offset = position & 31;
        var words = TwoOverPi.Words;
        var four = ((UInt128)words[word] << 96) | ((UInt128)words[word + 1] << 64) | ((UInt128)words[word + 2] << 32) | words[word + 3];
        var window = (four << offset) >> 32;

        // product·2^-shift is x·(2/π) mod 4, plus at most 2^-70 from the bits after the window.
        var product = significand * window;
        var shift = 95 + first - exponent;
        var half = UInt128.One << (shift - 1);
        var rounded = product + half;
        var quadrant = (int)(uint)(rounded >> shift) & 3;
        var fraction = rounded & ((UInt128.One << shift) - UInt128.One);
        var negative = fraction < half;
        var magnitude = negative ? half - fraction : fraction - half;

        // |f| = magnitude·2^-shift, never 0: that would take 70 zero bits in a row of 2/π inside the
        // window. Normalise its top 64 bits and multiply by π/2 in Q62.
        var leading = (int)UInt128.LeadingZeroCount(magnitude);
        var top = (ulong)((magnitude << leading) >> 64);
        var radians = (UInt128)top * HalfPiQ62;
        var normalise = (int)UInt128.LeadingZeroCount(radians);
        radians <<= normalise;
        var scale = 2 - shift - leading - normalise;

        // One rounding to 24 bits, ties to even; the tail is the next 24 bits of what is left.
        var high = (uint)(radians >> 104);
        var rest = radians & ((UInt128.One << 104) - UInt128.One);
        var halfway = UInt128.One << 103;
        var up = rest > halfway || (rest == halfway && (high & 1u) != 0);
        if (up)
        {
            high += 1u;
            rest = (UInt128.One << 104) - rest;
        }

        var lowBits = (uint)(rest >> 80);
        var resultHigh = System.MathF.ScaleB(high, 104 + scale);
        var resultLow = System.MathF.ScaleB(lowBits, 80 + scale);
        if (up)
        {
            resultLow = -resultLow;
        }

        r = negative ? -resultHigh : resultHigh;
        tail = negative ? -resultLow : resultLow;
        return quadrant;
    }

    /// <summary>sin(x + y) for |x| ≤ π/4 and |y| ≤ ulp(x)/2: x + x³·S(x²) + y·(1 − x²/2), degree 7.</summary>
    private static float SinKernel(float x, float y)
    {
        var z = x * x;
        var v = z * x;
        var p = SinS1 + (z * (SinS2 + (z * SinS3)));
        return x + ((v * p) + (y - ((0.5f * z) * y)));
    }

    /// <summary>
    /// cos(x + y) for |x| ≤ π/4: 1 − x²/2 + x⁴·C(x²) − x·y, degree 10, with fdlibm-style compensation of
    /// the rounding of 1 − x²/2.
    /// </summary>
    private static float CosKernel(float x, float y)
    {
        var z = x * x;
        var r = z * (CosC1 + (z * (CosC2 + (z * (CosC3 + (z * CosC4))))));
        var hz = 0.5f * z;
        var w = 1f - hz;
        return w + (((1f - w) - hz) + ((z * r) - (x * y)));
    }

    /// <summary>
    /// tan(x + y) for |x| ≤ π/4, degree 15, or −1/tan(x + y) when <paramref name="odd"/>, through an
    /// accurate reciprocal: both the divisor and the quotient are split into 12-bit heads, so the
    /// residual 1 + t·head is exact.
    /// </summary>
    private static float TanKernel(float x, float y, bool odd)
    {
        var z = x * x;
        var v = z * x;
        var p = TanT1 + (z * (TanT2 + (z * (TanT3 + (z * (TanT4 + (z * (TanT5 + (z * (TanT6 + (z * TanT7)))))))))));
        var correction = (v * p) + (y + (z * y));
        var w = x + correction;
        if (!odd)
        {
            return w;
        }

        var head = KeepTwelveBits(w);
        var headRest = correction - (head - x);
        var a = -1f / w;
        var t = KeepTwelveBits(a);
        var s = 1f + (t * head);
        return t + (a * (s + (t * headRest)));
    }

    /// <summary>The shared asin polynomial R(z) = z·(A0 + z·(A1 + … + z·A4)), degree 5, with asin(x) ≈ x + x·R(x²) for |x| ≤ ½.</summary>
    private static float AsinPolynomial(float z) =>
        z * (AsinA0 + (z * (AsinA1 + (z * (AsinA2 + (z * (AsinA3 + (z * AsinA4))))))));

    /// <summary>The atan polynomial Q(z) = z·(B0 + z·(B1 + … + z·B5)), with atan(x) ≈ x − x·Q(x²) for |x| ≤ 7/16.</summary>
    private static float AtanPolynomial(float z) =>
        z * (AtanB0 + (z * (AtanB1 + (z * (AtanB2 + (z * (AtanB3 + (z * (AtanB4 + (z * AtanB5))))))))));

    /// <summary><paramref name="value"/> with the low 12 bits of its significand cleared, toward zero.</summary>
    private static float KeepTwelveBits(float value) =>
        BitConverter.UInt32BitsToSingle(BitConverter.SingleToUInt32Bits(value) & TwelveBitMask);

    /// <summary>A positive normal binary32 value whose lowest set bit is at least 2^-62, in Q62 fixed point.</summary>
    private static ulong Q62(float part)
    {
        var bits = BitConverter.SingleToUInt32Bits(part);
        var significand = (ulong)((bits & 0x007FFFFFu) | 0x00800000u);
        var exponent = (int)(bits >> 23) - 150;
        return significand << (exponent + 62);
    }
