#!/usr/bin/env python3
"""Writes SimMath's generated C# constants (spec 015, research.md R3).

    emit_cs.py --out src/MmoEngine.SimCore/Math   writes SimMathCoefficients.g.cs and TwoOverPi.g.cs
    emit_cs.py --list                             prints "name 0xXXXXXXXX" per SimMathCoefficients constant

A clean-room offline tool: run it in a throwaway virtual environment with tools/simcore/requirements.txt
installed, never in CI. The --list lines are pasted into SimMathTests.CoefficientLines
(tests/MmoEngine.SimCore.Tests/Math/SimMathTests.cs), so a unit test pins every constant's bits.

SimMathCoefficients.g.cs holds `const float` literals only, so it has no executable code.
TwoOverPi.g.cs holds the 320 bits of 2/pi as a ReadOnlySpan<uint> over constant data, which the
compiler emits as RVA data: no allocation and no static field.
"""

import argparse
import os
import sys

import mpmath

import gen_coeffs
import gen_twoopi

HEADER = """\
// <auto-generated>
// Generated by tools/simcore/emit_cs.py (specs/015-shared-simulation-core/research.md R3).
// Do not edit by hand: change the generator in tools/simcore/ and rerun it, then update the pinned
// bits in tests/MmoEngine.SimCore.Tests/Math/SimMathTests.cs with `emit_cs.py --list`.
// </auto-generated>
"""


def float_literal(value):
    """A C# float literal that parses back to exactly this binary32 value."""
    bits = gen_coeffs.f32_bits(value)
    for digits in range(6, 10):
        text = mpmath.nstr(value, digits, strip_zeros=False, min_fixed=-4, max_fixed=4)
        text = text.replace("e-0", "e-").replace("e+", "e")
        if gen_coeffs.f32_bits(gen_coeffs.to_f32(mpmath.mpf(text))) == bits:
            return f"{text}f"
    raise ValueError(f"no literal of at most 9 digits round-trips 0x{bits:08X}")


def coefficients_source(rows):
    lines = [
        HEADER,
        "namespace MmoEngine.SimCore.Math;",
        "",
        "/// <summary>",
        "/// The binary32 constants of <see cref=\"SimMath\"/>: the kernel polynomial coefficients (weighted",
        "/// Remez fits rounded to binary32 one coefficient at a time) and the split constants of the range",
        "/// reductions. Generated by tools/simcore/emit_cs.py; every constant's bits are pinned by",
        "/// SimMathTests.CoefficientsHaveTheirPinnedBits.",
        "/// </summary>",
        "internal static class SimMathCoefficients",
        "{",
    ]
    for index, (name, value, comment) in enumerate(rows):
        if index > 0:
            lines.append("")
        bits = gen_coeffs.f32_bits(value)
        lines.append(f"    /// <summary>{comment} (0x{bits:08X}).</summary>")
        lines.append(f"    internal const float {name} = {float_literal(value)};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def two_over_pi_source(words):
    rows = []
    for start in range(0, len(words), 5):
        rows.append("        " + ", ".join(f"0x{word:08X}u" for word in words[start:start + 5]) + ",")
    lines = [
        HEADER,
        "using System;",
        "",
        "namespace MmoEngine.SimCore.Math;",
        "",
        "/// <summary>",
        "/// The first 320 bits of 2/pi, read by the Payne-Hanek reduction of <see cref=\"SimMath\"/>. Word j",
        "/// holds the bits from 2^-(32j + 1) to 2^-(32j + 32), most significant first. Generated by",
        "/// tools/simcore/emit_cs.py; the words are pinned by SimMathTests.CoefficientsHaveTheirPinnedBits.",
        "/// </summary>",
        "internal static class TwoOverPi",
        "{",
        "    /// <summary>floor(2/pi * 2^320) as ten 32-bit words, most significant first: constant data, no allocation.</summary>",
        "    internal static ReadOnlySpan<uint> Words =>",
        "    [",
        *rows,
        "    ];",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", help="directory to write SimMathCoefficients.g.cs and TwoOverPi.g.cs into")
    parser.add_argument("--list", action="store_true", help="print 'name 0xXXXXXXXX' per SimMathCoefficients constant")
    args = parser.parse_args(argv)
    if not args.out and not args.list:
        parser.error("pass --out DIRECTORY, --list, or both")

    rows, reports = gen_coeffs.constants()
    if args.list:
        for name, value, _ in rows:
            print(f"{name} 0x{gen_coeffs.f32_bits(value):08X}")
    if args.out:
        for line in reports:
            print(line, file=sys.stderr)
        files = {
            "SimMathCoefficients.g.cs": coefficients_source(rows),
            "TwoOverPi.g.cs": two_over_pi_source(gen_twoopi.two_over_pi_words()),
        }
        for file_name, text in files.items():
            path = os.path.join(args.out, file_name)
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            print(f"wrote {path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
